def campos_de_perfil(tipo):
    """Campos del perfil que aplican a un tipo de usuario."""
    return [c for c in PERFIL if c['roles'] == 'ambos' or c['roles'] == tipo]


def campo_perfil(campo, valor=None):
    """Valor por defecto de un campo, resuelto para el tipo de usuario."""
    if valor is not None:
        return valor
    if campo.get('def'):
        return campo['def']
    return ''

